export function buildPlan(type='consult', extras=[]) {
  if(!Object.hasOwn(PRESETS,type)) throw new Error('지원하지 않는 폼 유형입니다.');
  const selected=[...new Set(Array.isArray(extras)?extras:[])].filter(key=>Object.hasOwn(EXTRA_FIELDS,key));
  const preset=PRESETS[type];
  return {
    ...preset,
    fields:[...preset.fields.map(field=>[...field]),...selected.map(key=>[...EXTRA_FIELDS[key]])],
    selected,
    checks:[
      '페이지 첫 화면에서 신청 목적과 응답 방식을 알 수 있는가?',
      '실제 필요하지 않은 개인정보 항목을 제외했는가?',
      '개인정보 수집 목적·항목·보유 기간·동의를 운영 기준에 맞게 표시했는가?',
      '중복 접수·필수 입력·모바일 키보드와 선택지를 시험했는가?',
      '제출 완료 문구와 접수함 저장 기록이 일치하는가?',
      '발행한 공개 주소에서 마지막으로 시험 접수했는가?',
    ],
  };
}
export function planAsText(plan) {
  return ['[페이지로 신청폼 구성안 — 실제 운영 전 검토용]',plan.heading,'',
    '추천 입력 항목',...plan.fields.map(f=>'- '+f[0]+' ('+f[1]+', '+f[2]+'): '+f[3]),'',
    '제출 버튼: '+plan.submit,'완료 문구: '+plan.complete,'주의: '+plan.caution,'',
    '적용·검증 단계',...plan.flow.map((s,i)=>(i+1)+'. '+s),'',
    '최종 점검',...plan.checks.map(s=>'[ ] '+s),
    '※ 추천 구성안입니다. 실제 개인정보 처리방침과 운영 방식은 별도로 확인하세요.',
    '설명서: https://pagero.kr'+plan.guide].join('\n');
}
