import assert from 'node:assert/strict';
import { onRequest } from '../functions/index.js';
import { PUBLIC_HOME_MARKUP } from '../src/screens/publicHomeMarkup.js';
const response=onRequest();
const html=await response.text();
assert.equal(response.status,200);
assert(html.includes(PUBLIC_HOME_MARKUP),'Actual Cloudflare homepage and React must share the same real content');
assert(html.includes('href="/guide/"')&&html.includes('href="/tools/lead-calculator/"'),'Publisher tools must be available to visitors and crawlers');
assert(html.includes('href="/life/"')&&html.includes('https://calltag.pagero.kr/'),'LIFE and CallTag partner-service links must remain');
assert(html.includes('name="google-adsense-account"'),'Publisher AdSense verification must remain');
assert(html.includes('href="/login"')&&html.includes('href="/signup"'),'Customer login and signup links required');
assert(!html.includes('c63-assets/'),'The frozen C63 marketing JS must no longer own the root page');
assert(!html.includes('c63-life-bridge.js'),'No obsolete DOM-injection bridge on canonical home');
assert(!html.includes('pagead2.googlesyndication.com'),'No automatic ad script on shared editor routes');
console.log('PASS: real canonical PageRo root, working product resources, LIFE/CallTag discovery, and AdSense identity.');
